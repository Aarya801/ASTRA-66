def chart(sens, R):
    W, H = 720, 330
    l, r, t, b = 58, 20, 24, 50
    xs = [s["motor_m"] for s in sens]
    x0, x1 = min(xs), max(xs)
    y0, y1 = 0.0, 4.0

    def px(v):
        return l + (v - x0) / (x1 - x0) * (W - l - r)

    def py(v):
        return t + (1 - (v - y0) / (y1 - y0)) * (H - t - b)
    o = [f'<svg viewBox="0 0 {W} {H}" class="chart" role="img" aria-label="Static stability margin at liftoff versus loaded motor mass; stays between {sens[-1]["sm"]:.2f} and {sens[0]["sm"]:.2f} calibres over 40 to 320 grams">']
    o.append(f'<rect x="{l}" y="{py(3.0):.1f}" width="{W - l - r}" height="{py(1.5) - py(3.0):.1f}" class="band"/>')
    o.append(f'<text x="{W - r - 6}" y="{py(3.0) + 14:.1f}" text-anchor="end" class="bandlab">TARGET 1.5–3.0 CAL</text>')
    for yv in (0, 1, 2, 3, 4):
        o.append(f'<line x1="{l}" x2="{W - r}" y1="{py(yv):.1f}" y2="{py(yv):.1f}" class="grid"/>')
        o.append(f'<text x="{l - 8}" y="{py(yv) + 4:.1f}" text-anchor="end" class="ax">{yv}</text>')
    for xv in range(40, 321, 40):
        o.append(f'<text x="{px(xv):.1f}" y="{H - b + 18}" text-anchor="middle" class="ax">{xv}</text>')
    o.append(f'<text x="{(l + W - r) / 2}" y="{H - 8}" text-anchor="middle" class="axt">Loaded motor mass, g (motor CG held at placeholder station)</text>')
    o.append(f'<text x="14" y="{(t + H - b) / 2}" text-anchor="middle" class="axt" transform="rotate(-90 14 {(t + H - b) / 2})">Static margin, cal</text>')
    pts = " ".join(f"{px(s['motor_m']):.1f},{py(s['sm']):.1f}" for s in sens)
    area = f"{px(x0):.1f},{py(0):.1f} " + pts + f" {px(x1):.1f},{py(0):.1f}"
    o.append(f'<polygon points="{area}" class="area"/>')
    o.append(f'<polyline points="{pts}" class="series"/>')
    for s in sens:
        hi = s["motor_m"] == int(A.MOTOR_M0)
        o.append(f'<circle cx="{px(s["motor_m"]):.1f}" cy="{py(s["sm"]):.1f}" r="{5 if hi else 3}" class="{"pt hi" if hi else "pt"}"/>')
        o.append(f'<rect x="{px(s["motor_m"]) - 12:.1f}" y="{t}" width="24" height="{H - t - b}" class="hit" '
                 f'data-m="{s["motor_m"]}" data-sm="{s["sm"]:.2f}" data-cg="{s["cg"]:.0f}" data-mass="{s["M"]:.0f}" data-x="{px(s["motor_m"]):.1f}" data-y="{py(s["sm"]):.1f}"/>')
    ph = [s for s in sens if s["motor_m"] == int(A.MOTOR_M0)][0]
