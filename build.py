def esc(s):
    return html.escape(str(s))


def tag(t):
    key = t.split()[0].split("→")[0].split("(")[0].strip()
    cls = {"CALC": "calc", "ASM": "asm", "USER": "user", "COTS": "cots"}.get(key, "asm")
    label = TAGNAME.get(key, t)
    return f'<span class="tag t-{cls}">{esc(label)}</span>'


def tbl(headers, rows, cls="", num=(), raw=(), foot=None, caption=None):
    h = "".join(f'<th{" class=num" if i in num else ""}>{esc(x)}</th>' for i, x in enumerate(headers))
    body = []
    for r in rows:
        tds = []
        for i, c in enumerate(r):
            v = c if i in raw else esc(c)
            tds.append(f'<td{" class=num" if i in num else ""}>{v}</td>')
        body.append("<tr>" + "".join(tds) + "</tr>")
    ft = ""
    if foot:
        ft = "<tfoot><tr>" + "".join(f'<td{" class=num" if i in num else ""}>{c}</td>' for i, c in enumerate(foot)) + "</tr></tfoot>"
    cap = f"<caption>{esc(caption)}</caption>" if caption else ""
    return f'<div class="tw"><table class="{cls}">{cap}<thead><tr>{h}</tr></thead><tbody>{"".join(body)}</tbody>{ft}</table></div>'


def n(v, d=0):
    return f"{v:,.{d}f}"


def money(lo, hi):
    return f"${lo:,.0f}–{hi:,.0f}"


